#!/usr/bin/env python3
"""Generate the short startup BOOT.md from indexed context pointers."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from context_common import (
    CONTROL_DIR_REL,
    GENERATED_DIR_REL,
    INDEX_DIR_REL,
    LOG_DIR_REL,
    append_jsonl,
    char_count,
    ensure_dirs,
    line_count,
    read_csv,
    read_json,
    relpath,
    sha256_file,
    utc_now,
    write_csv,
    write_json,
    write_json_with_self_sha,
    write_script_audit,
)


SOURCE_FIELDS = [
    "artifact_path",
    "artifact_role",
    "sha256",
    "authority_level",
    "read_policy",
    "included_in_boot",
    "notes",
]


BUILD_FIELDS = ["artifact_path", "artifact_role", "sha256", "created_at_utc", "notes"]


def first_open_gap(root: Path) -> dict[str, str]:
    rows = read_csv(root / INDEX_DIR_REL / "GAP_INDEX.csv")
    for row in rows:
        if row.get("status", "").upper() not in {"CLOSED", "RESOLVED"}:
            return row
    return {}


def source_row(root: Path, rel: str, role: str, included: bool = True, notes: str = "") -> dict[str, str]:
    return {
        "artifact_path": rel,
        "artifact_role": role,
        "sha256": sha256_file(root / rel),
        "authority_level": "",
        "read_policy": "pointer",
        "included_in_boot": "TRUE" if included else "FALSE",
        "notes": notes,
    }


DEFAULT_BOOT_RULE_KEYWORDS = ["holdout", "side effect", "recursive", "boot.md"]


def load_rule_subset(invariants: dict[str, Any]) -> list[str]:
    """Pick the invariant rules that BOOT.md repeats.

    SYSTEM_INVARIANTS.json may set "boot_rule_keywords"; a rule is kept when it
    contains one of them. At most nine rules are kept.
    """
    rules = [str(rule) for rule in invariants.get("rules", [])]
    keywords = invariants.get("boot_rule_keywords") or DEFAULT_BOOT_RULE_KEYWORDS
    tokens = [str(token).lower() for token in keywords]
    keep = []
    for rule in rules:
        lower = rule.lower()
        if any(token in lower for token in tokens):
            keep.append(rule)
    return keep[:9]


def generate_boot(root: Path) -> tuple[str, list[dict[str, str]]]:
    invariants_path = root / "context/SYSTEM_INVARIANTS.json"
    task_path = root / "context/TASK_STATE.json"
    current_verdict_path = root / "context/CURRENT_VERDICT.json"
    active_project_path = root / "context/global/ACTIVE_PROJECT.json"
    file_index_path = root / INDEX_DIR_REL / "FILE_INDEX.csv"

    invariants = read_json(invariants_path, {})
    task = read_json(task_path, {})
    current_verdict = read_json(current_verdict_path, {})
    active_project = read_json(active_project_path, {})
    boot_limits = invariants.get("boot_limits", {})
    gap = first_open_gap(root)
    active_project_id = active_project.get("active_project_id", "default")

    lines: list[str] = [
        "# BOOT",
        "Generated by `tools/context/build_boot_context.py`; edit sources, then regenerate.",
        "",
        "Purpose: load the smallest runnable context for this workspace.",
        "This file is a pointer map, not a project summary.",
        "",
        "## Hard Rules",
    ]
    for rule in load_rule_subset(invariants):
        lines.append(f"- {rule}")

    lines.extend(
        [
            "",
            "## Startup Read Order",
            "1. `context/global/ACTIVE_PROJECT.json` and `PROJECT_REGISTRY.json` for project routing.",
            "2. `context/SYSTEM_INVARIANTS.json` for immutable constraints.",
            "3. `context/TASK_STATE.json` and `context/CURRENT_VERDICT.json` for status.",
            "4. `context/generated/startup_bundles/default_STARTUP_BUNDLE.md`.",
            "5. `context/indexes/views/*_VIEW.csv`; query full indexes only with `tools/context/query_index.py`.",
            "",
            "## Current Pointers",
            f"- Active project: `{active_project_id}`",
            f"- Phase: `{task.get('current_phase', 'unknown')}`",
            f"- Runner: `{task.get('current_runner', 'tools/context/run_context_control_all.sh')}`",
            f"- Next action: `{task.get('next_allowed_action', 'Run tools/context/run_context_control_all.sh')}`",
            f"- Integrity: `{task.get('context_integrity_status', current_verdict.get('verdict', 'UNKNOWN'))}`",
            f"- Holdout state: `{task.get('holdout_status', invariants.get('holdout_status_required', 'LOCKED'))}`",
            f"- Latest gap queue: `{task.get('latest_gap_queue_path', str(CONTROL_DIR_REL / 'gap_queue.csv'))}`",
            f"- Latest verdict: `{task.get('latest_verdict_path', 'context/CURRENT_VERDICT.json')}`",
            "",
            "## Startup-Safe Views",
            "- `context/indexes/views/FILE_INDEX_VIEW.csv` - bounded artifact map.",
            "- `context/indexes/views/RUNNER_INDEX_VIEW.csv` - runnable contracts.",
            "- `context/indexes/views/CASE_INDEX_VIEW.csv` - bounded case metadata.",
            "- `context/indexes/views/EVIDENCE_INDEX_VIEW.csv` - source pointers only.",
            "- `context/indexes/views/GAP_INDEX_VIEW.csv` - prioritized gap pointers.",
            "",
            "## First Open Gap",
        ]
    )
    if gap:
        lines.extend(
            [
                f"- Type: `{gap.get('gap_type', 'unknown')}`",
                f"- Severity: `{gap.get('severity', 'INFO')}` / `{gap.get('blocking_level', 'NON_BLOCKING')}`",
                f"- Action: {gap.get('next_action', 'Review GAP_INDEX.csv')}",
            ]
        )
    else:
        lines.append("- None indexed.")

    lines.extend(
        [
            "",
            "## Authority Rule",
            "- Higher-authority source pointers outrank generated summaries.",
            "- Generated files may compress navigation only; they cannot override sources.",
            "- On conflict, stop and record the blocker in the control gap queue.",
            "",
            "## Startup Boundary",
            "- Keep BOOT under 80 lines and 4000 characters.",
            "- Do not add recursive entry files.",
            "- Do not load long histories, case bodies, source bodies, or wide tables at startup.",
            "- Do not touch external side-effect interfaces (payments, deployments, account changes).",
            "",
            "## Regeneration",
            "- Run `tools/context/run_context_governor_all.sh` after context edits.",
            "- The run writes audits under `var/context_governor_2026_06_24/audit/`.",
        ]
    )
    text = "\n".join(lines).rstrip() + "\n"

    max_lines = int(boot_limits.get("max_lines", 80))
    max_chars = int(boot_limits.get("max_chars", 4000))
    if len(text.splitlines()) > max_lines or len(text) > max_chars:
        raise RuntimeError(
            f"Generated BOOT exceeds limits: {len(text.splitlines())}/{max_lines} lines, {len(text)}/{max_chars} chars"
        )

    sources = [
        source_row(root, "context/SYSTEM_INVARIANTS.json", "invariant"),
        source_row(root, "context/TASK_STATE.json", "state"),
        source_row(root, "context/CURRENT_VERDICT.json", "verdict"),
        source_row(root, "context/global/ACTIVE_PROJECT.json", "project_router"),
        source_row(root, "context/global/PROJECT_REGISTRY.json", "project_registry"),
        source_row(root, "context/indexes/views/FILE_INDEX_VIEW.csv", "index_view"),
        source_row(root, "context/indexes/views/RUNNER_INDEX_VIEW.csv", "index_view"),
        source_row(root, "context/indexes/views/CASE_INDEX_VIEW.csv", "index_view"),
        source_row(root, "context/indexes/views/EVIDENCE_INDEX_VIEW.csv", "index_view"),
        source_row(root, "context/indexes/views/GAP_INDEX_VIEW.csv", "index_view"),
    ]
    for row in sources:
        index_match = next((item for item in read_csv(file_index_path) if item.get("path") == row["artifact_path"]), {})
        row["authority_level"] = index_match.get("authority_level", "")
        row["read_policy"] = index_match.get("read_policy", row["read_policy"])
    return text, sources


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".")
    args = parser.parse_args()
    root = Path(args.root).expanduser().resolve()
    ensure_dirs(root)

    text, sources = generate_boot(root)
    boot_path = root / "BOOT.md"
    boot_path.write_text(text, encoding="utf-8")

    now = utc_now()
    source_manifest_path = root / GENERATED_DIR_REL / "BOOT_SOURCE_MANIFEST.csv"
    build_manifest_path = root / GENERATED_DIR_REL / "BOOT_BUILD_MANIFEST.csv"
    write_csv(source_manifest_path, SOURCE_FIELDS, sources)
    build_rows = [
        {
            "artifact_path": "BOOT.md",
            "artifact_role": "generated_startup_pointer",
            "sha256": sha256_file(boot_path),
            "created_at_utc": now,
            "notes": "short generated boot context",
        },
        {
            "artifact_path": relpath(root, source_manifest_path),
            "artifact_role": "source_manifest",
            "sha256": sha256_file(source_manifest_path),
            "created_at_utc": now,
            "notes": "sources used by BOOT.md",
        },
    ]
    write_csv(build_manifest_path, BUILD_FIELDS, build_rows)

    summary = {
        "script": "build_boot_context.py",
        "created_at_utc": now,
        "boot_path": "BOOT.md",
        "boot_line_count": line_count(boot_path),
        "boot_char_count": char_count(boot_path),
        "source_manifest_path": relpath(root, source_manifest_path),
        "build_manifest_path": relpath(root, build_manifest_path),
    }
    verdict = {
        "script": "build_boot_context.py",
        "created_at_utc": now,
        "verdict": "BOOT_CONTEXT_BUILT",
        "hard_blocker": False,
        "boot_within_limits": summary["boot_line_count"] <= 80 and summary["boot_char_count"] <= 4000,
    }
    current = {
        "current_verdict_version": "1.0",
        "updated_at_utc": now,
        "verdict": "BOOT_CONTEXT_BUILT",
        "hard_blocker": False,
        "latest_summary_path": str(CONTROL_DIR_REL / "summary.json"),
        "latest_report_path": "",
        "notes": "Integrity check has not yet written the final verdict for this run.",
    }
    write_json(root / CONTROL_DIR_REL / "summary.json", summary)
    write_json(root / CONTROL_DIR_REL / "verdict.json", verdict)
    write_json_with_self_sha(root / "context/CURRENT_VERDICT.json", current)
    write_script_audit(root, "build_boot_context", summary, verdict, build_rows)
    append_jsonl(root / LOG_DIR_REL / "CONTEXT_BUILD_LOG.jsonl", {"event": "boot_built", **summary})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
