#!/usr/bin/env python3
"""Tests for context integrity checks."""

from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

from context_common import ensure_dirs, write_csv, write_json
from context_integrity_check import run_checks


def make_fixture() -> tempfile.TemporaryDirectory[str]:
    tmp = tempfile.TemporaryDirectory()
    root = Path(tmp.name)
    ensure_dirs(root)
    (root / "BOOT.md").write_text(
        "\n".join(
            [
                "# BOOT",
                "Generated by `tools/context/build_boot_context.py`; edit sources, then regenerate.",
                "Purpose: pointer map only.",
                "BOOT.md is a pointer map, not a project summary.",
                "Holdout samples stay locked.",
                "Generated summaries never outrank sources.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    write_json(
        root / "context/SYSTEM_INVARIANTS.json",
        {"boot_limits": {"max_lines": 80, "max_chars": 4000}, "holdout_status_required": "LOCKED"},
    )
    write_json(
        root / "context/TASK_STATE.json",
        {
            "current_runner": "tools/context/run_context_control_all.sh",
            "latest_verdict_path": "context/CURRENT_VERDICT.json",
            "latest_gap_queue_path": "var/context_control_2026_06_23/gap_queue.csv",
            "holdout_status": "LOCKED",
        },
    )
    write_json(root / "context/CURRENT_VERDICT.json", {"verdict": "OK"})
    (root / "tools/context/run_context_control_all.sh").write_text("#!/usr/bin/env bash\n", encoding="utf-8")
    write_csv(
        root / "context/indexes/RUNNER_INDEX.csv",
        ["path", "status", "authority_level"],
        [{"path": "tools/context/run_context_control_all.sh", "status": "ACTIVE", "authority_level": "85"}],
    )
    write_csv(
        root / "context/indexes/FILE_INDEX.csv",
        ["path", "artifact_type", "authority_level", "source_of_truth"],
        [{"path": "BOOT.md", "artifact_type": "boot", "authority_level": "50", "source_of_truth": "FALSE"}],
    )
    write_csv(root / "context/indexes/GAP_INDEX.csv", ["gap_id", "status"], [])
    write_csv(root / "var/context_control_2026_06_23/gap_queue.csv", ["gap_id"], [])
    return tmp


class ContextIntegrityTests(unittest.TestCase):
    def test_clean_fixture_passes(self) -> None:
        with make_fixture() as tmp:
            result = run_checks(Path(tmp))
            self.assertEqual(result["summary"]["verdict"], "CONTEXT_INTEGRITY_PASS")

    def test_semantic_drift_fails(self) -> None:
        with make_fixture() as tmp:
            root = Path(tmp)
            (root / "BOOT.md").write_text("BOOT.md is the full project summary\n", encoding="utf-8")
            result = run_checks(root)
            self.assertEqual(result["summary"]["verdict"], "CONTEXT_INTEGRITY_FAIL_SEMANTIC_DRIFT")

    def test_forbidden_boot_content_fails(self) -> None:
        with make_fixture() as tmp:
            root = Path(tmp)
            (root / "BOOT.md").write_text("results table\n| entity_key | result |\n", encoding="utf-8")
            result = run_checks(root)
            self.assertEqual(result["summary"]["verdict"], "CONTEXT_INTEGRITY_FAIL_SEMANTIC_DRIFT")


if __name__ == "__main__":
    unittest.main()
